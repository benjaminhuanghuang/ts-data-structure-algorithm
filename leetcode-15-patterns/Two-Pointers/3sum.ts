/*

3Sum


Talk-through: Sort first. Fix nums[i] as the smallest of the triple, then
two-pointer the remaining range for a pair summing to -nums[i]. Skip
duplicate values for i, left, and right to avoid duplicate triples — the
skip only matters once a match or move has already happened.

Time big O of n^2, space big O of 1 extra (ignoring sort / output).
*/
function threeSum(nums: number[]): number[][] {
  nums.sort((a, b) => a - b);
  const result: number[][] = [];

  for (let i = 0; i < nums.length - 2; i++) {
    if (i > 0 && nums[i] === nums[i - 1]) continue;
    if (nums[i] > 0) break;

    let left = i + 1;
    let right = nums.length - 1;

    while (left < right) {
      const sum = nums[i] + nums[left] + nums[right];
      if (sum === 0) {
        result.push([nums[i], nums[left], nums[right]]);
        left++;
        right--;
        while (left < right && nums[left] === nums[left - 1]) left++;
        while (left < right && nums[right] === nums[right + 1]) right--;
      } else if (sum < 0) {
        left++;
      } else {
        right--;
      }
    }
  }

  return result;
}
